void main() {
  String day = "Monday";

  switch (day) {
    case "Monday":
      print("Today is Monday - Start your week!");
      break;

    case "Tuesday":
      print("Today is Tuesday - Keep going!");
      break;

    case "Wednesday":
      print("Today is Wednesday - Halfway through the week!");
      break;

    case "Thursday":
      print("Today is Thursday - Almost there!");
      break;

    case "Friday":
      print("Today is Friday - Weekend is near!");
      break;

    case "Saturday":
      print("Today is Saturday - Enjoy your weekend!");
      break;

    case "Sunday":
      print("Today is Sunday - Relax and prepare for Monday!");
      break;

    default:
      print("Invalid day");
  }
}
